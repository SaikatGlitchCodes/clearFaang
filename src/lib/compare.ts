// Hand-written comparison notes for the "drop one service on another" popup.
// Ranks are 1 (weak) to 5 (strong) and are relative judgements, not benchmarks.

export interface Ranks {
  /** how far it scales */
  scale: number;
  /** how low and steady the latency is */
  latency: number;
  /** how little operational work it needs */
  simple: number;
  /** how cheap it is for a small or medium workload */
  cheap: number;
}

export interface CompareInfo {
  tag: string;
  scales: string;
  guarantees: string;
  latency: string;
  ops: string;
  pricing: string;
  use: string[];
  avoid: string[];
  ranks: Ranks;
}

const r = (scale: number, latency: number, simple: number, cheap: number): Ranks => ({ scale, latency, simple, cheap });

